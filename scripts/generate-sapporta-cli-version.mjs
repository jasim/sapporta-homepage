import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const SAPPORTA_LATEST_URL = "https://registry.npmjs.org/sapporta/latest";

const outputUrl = new URL(
  "../packages/docs/src/generated/sapporta-cli.mjs",
  import.meta.url,
);
const semverPattern =
  /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-((?:0|[1-9]\d*|\d*[A-Za-z-][0-9A-Za-z-]*)(?:\.(?:0|[1-9]\d*|\d*[A-Za-z-][0-9A-Za-z-]*))*))?(?:\+([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?$/;

export function parseLatestVersion(payload) {
  if (
    typeof payload !== "object" ||
    payload === null ||
    Array.isArray(payload)
  ) {
    throw new Error("npm registry response must be a JSON object");
  }

  if (payload.name !== "sapporta") {
    throw new Error(
      `npm registry returned metadata for the wrong package: ${JSON.stringify(payload.name)}`,
    );
  }

  const version = payload.version;
  if (typeof version !== "string" || !semverPattern.test(version)) {
    throw new Error(
      `npm registry returned an invalid sapporta version: ${JSON.stringify(version)}`,
    );
  }

  return version;
}

export function renderGeneratedModule(version) {
  if (!semverPattern.test(version)) {
    throw new Error(
      `Refusing to generate data for an invalid sapporta version: ${JSON.stringify(version)}`,
    );
  }

  return [
    "// Generated by scripts/generate-sapporta-cli-version.mjs. Do not edit.",
    `export const sapportaCliVersion = ${JSON.stringify(version)};`,
    "export const sapportaInitCommand = `pnpm dlx sapporta@${sapportaCliVersion} init my-app`;",
    "",
  ].join("\n");
}

export async function resolveLatestVersion(
  fetchImplementation = globalThis.fetch,
) {
  if (typeof fetchImplementation !== "function") {
    throw new Error("This build requires a Node.js runtime with fetch support");
  }

  let response;
  try {
    response = await fetchImplementation(SAPPORTA_LATEST_URL, {
      headers: { accept: "application/json" },
      signal: AbortSignal.timeout(15_000),
    });
  } catch (error) {
    throw new Error(
      `Could not reach npm to resolve sapporta@latest from ${SAPPORTA_LATEST_URL}`,
      {
        cause: error,
      },
    );
  }

  if (!response.ok) {
    throw new Error(
      `npm registry request for sapporta@latest failed with ${response.status} ${response.statusText}`.trim(),
    );
  }

  let payload;
  try {
    payload = await response.json();
  } catch (error) {
    throw new Error("npm registry returned invalid JSON for sapporta@latest", {
      cause: error,
    });
  }

  return parseLatestVersion(payload);
}

export async function writeGeneratedModule(version, destination = outputUrl) {
  const content = renderGeneratedModule(version);
  const destinationPath = fileURLToPath(destination);

  let currentContent;
  try {
    currentContent = await readFile(destination, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }

  if (currentContent === content) return false;

  await mkdir(dirname(destinationPath), { recursive: true });
  await writeFile(destination, content, "utf8");
  return true;
}

async function main() {
  try {
    const version = await resolveLatestVersion();
    await writeGeneratedModule(version);
    console.log(
      `Resolved sapporta@latest as ${version} from ${SAPPORTA_LATEST_URL}`,
    );
  } catch (error) {
    console.error(
      `Failed to generate the homepage Sapporta CLI version: ${error.message}`,
    );
    if (error.cause instanceof Error)
      console.error(`Cause: ${error.cause.message}`);
    process.exitCode = 1;
  }
}

const isDirectExecution =
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(process.argv[1]).href;

if (isDirectExecution) await main();
